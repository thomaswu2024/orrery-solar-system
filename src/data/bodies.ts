export type BodyKind = 'star' | 'planet' | 'dwarf' | 'moon'

export interface OrbitalRates {
  a: number
  e: number
  inclination: number
  node: number
  peri: number
  meanLongitude: number
}

/**
 * Heliocentric bodies use JPL approximate elements (a in AU), valid 1800–2050.
 * Satellites use parent-centric elements (a in km) with a fixed period.
 * Angles in degrees, epoch J2000.0 (JD 2451545.0).
 */
export interface OrbitalElements {
  a: number
  e: number
  inclination: number
  node: number
  peri: number
  meanLongitude?: number
  meanAnomaly?: number
  meanMotion?: number
  periodDays: number
  rates?: OrbitalRates
}

export interface AtmosphereDef {
  color: string
  intensity: number
  scale: number
  power?: number
}

export interface RingDef {
  inner: number
  outer: number
  opacity: number
  texture: string
}

